   execute format('select coalesce(jsonb_agg(payload order by position),''[]''::jsonb) from public.%I where workspace_id=$1','crm_'||entity) into entry using ws.id;
   if entry is distinct from part then raise exception 'Vérification de migration échouée : %',entity; end if;
