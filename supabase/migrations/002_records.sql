   n:=0;
   for entry in select value from jsonb_array_elements(part) loop
    n:=n+1;
    if jsonb_typeof(entry)<>'object' or coalesce(entry->>'id','')='' then raise exception 'Fiche sans identifiant dans %',entity; end if;
